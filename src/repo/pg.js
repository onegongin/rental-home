// Supabase(PostgreSQL) 통역기 (설계서 4.2, P8) — D1 과 똑같은 모양(prepare · bind · all · first · run · batch)을 흉내 낸다
//   그래서 업무 코드(repo/*.js · staff-api/*.js …)는 한 줄도 안 바꾸고 DB_DRIVER 만 바꾸면 된다
//   여기서 SQLite 문법 → PostgreSQL 문법으로 바꿔 보낸다:
//     ? → $1 · INTEGER → NUMERIC(정수 · 소수 다 받는 SQLite 처럼) · REAL → DOUBLE PRECISION
//     AUTOINCREMENT → IDENTITY · INSERT OR IGNORE → ON CONFLICT DO NOTHING · camelCase 별칭 → "따옴표"
//     ORDER BY 의 빈칸(NULL) 순서를 SQLite 와 같게 (오름차순 맨 앞 · 내림차순 맨 뒤)
//     표마다 숨은 rowid 칸(BIGSERIAL)을 붙여 백업의 'rowid' 를 그대로 씀 · sqlite_master · PRAGMA table_info 는 information_schema 로
//   결과: 참/거짓 → 1/0 (SQLite 처럼), 숨은 rowid 칸은 빼고 돌려줌
//   ex = { q(text, params) → { rows, count }, tx(async q => …) } — 실제 연결은 supabase.js, 시험은 PGlite

const AUTO = new Set();          // AUTOINCREMENT 표 (CREATE 때 알게 됨) — INSERT 뒤 last_row_id 용 RETURNING id
const cache = new Map();

// 따옴표 밖의 ? 만 $n 으로
function params(sql) {
  let out = '', n = 0, q = null;
  for (const ch of sql) {
    if (q) { if (ch === q) q = null; out += ch; continue; }
    if (ch === "'" || ch === '"') { q = ch; out += ch; continue; }
    out += ch === '?' ? '$' + (++n) : ch;
  }
  return out;
}

// 괄호 깊이 0 에서 쉼표로 나누기
function splitTop(s) {
  const out = []; let d = 0, cur = '', q = null;
  for (const ch of s) {
    if (q) { if (ch === q) q = null; cur += ch; continue; }
    if (ch === "'" || ch === '"') q = ch;
    else if (ch === '(') d++;
    else if (ch === ')') d--;
    if (ch === ',' && d === 0) { out.push(cur); cur = ''; continue; }
    cur += ch;
  }
  out.push(cur);
  return out;
}

// ORDER BY a, b DESC → ORDER BY a NULLS FIRST, b DESC NULLS LAST
function nullsLikeSqlite(sql) {
  return sql.replace(/ORDER BY ([^;]*?)(?=\s+LIMIT\b|\s+OFFSET\b|\)|$)/gi, (m, list) => {
    if (/\bNULLS\b/i.test(list)) return m;
    return 'ORDER BY ' + splitTop(list).map(t => {
      t = t.trim();
      return t + (/\bDESC$/i.test(t) ? ' NULLS LAST' : ' NULLS FIRST');
    }).join(', ');
  });
}

const typ = s => s.replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bINTEGER\b/gi, 'NUMERIC').replace(/\bREAL\b/gi, 'DOUBLE PRECISION');

export function toPg(sql) {
  const hit = cache.get(sql);
  if (hit) return hit;
  let s = sql.trim(), t;
  const out = { sql: s, meta: null };
  if (/^SELECT name FROM sqlite_master/i.test(s)) {
    out.sql = "SELECT table_name AS name FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' ORDER BY table_name";
  } else if ((t = s.match(/^PRAGMA table_info\("?([\w]+)"?\)$/i))) {
    out.sql = "SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '" + t[1] + "' AND column_name <> 'rowid' ORDER BY ordinal_position";
  } else if ((t = s.match(/^CREATE TABLE IF NOT EXISTS (\w+) \(/i))) {
    if (/AUTOINCREMENT/i.test(s)) AUTO.add(t[1]);
    out.sql = typ(s).replace(/\(/, '(rowid BIGSERIAL, ');
    out.meta = { create: t[1] };
  } else if (/^ALTER TABLE \w+ ADD COLUMN /i.test(s)) {
    out.sql = typ(s).replace(/ADD COLUMN /i, 'ADD COLUMN IF NOT EXISTS ');
  } else if (/^CREATE INDEX/i.test(s)) {
    out.sql = s;
  } else {
    if (/^INSERT OR IGNORE INTO/i.test(s)) s = s.replace(/^INSERT OR IGNORE INTO/i, 'INSERT INTO') + ' ON CONFLICT DO NOTHING';
    s = s.replace(/\bAS ([A-Za-z_]\w*)/g, (m, a) => /[A-Z]/.test(a) ? 'AS "' + a + '"' : m);
    s = nullsLikeSqlite(s);
    if ((t = s.match(/^INSERT INTO "?(\w+)"? \(([^)]*)\)/i))) {
      out.meta = { insert: t[1], ownId: /(^|[\s,"])id("?)(\s*,|\s*$)/.test(t[2]) };
      if (AUTO.has(t[1]) && !/RETURNING/i.test(s)) s += ' RETURNING id';
    }
    out.sql = params(s);
  }
  cache.set(sql, out);
  return out;
}

const val = v => v === true ? 1 : v === false ? 0 : v === undefined ? null : v;
const fixRow = r => {
  const o = {};
  for (const k in r) if (k !== 'rowid') o[k] = typeof r[k] === 'boolean' ? (r[k] ? 1 : 0) : r[k];
  return o;
};

// ex 하나(= 요청 하나의 연결)를 D1 처럼 보이게
export function pgD1(ex, key) {
  async function exec(q, st) {
    const p = toPg(st.sql);
    const r = await q(p.sql, st.args.map(val));
    if (p.meta && p.meta.create) await q('ALTER TABLE ' + p.meta.create + ' ENABLE ROW LEVEL SECURITY', []);   // Supabase 화면 · REST 로 못 읽게 (추가 방어)
    const rows = (r.rows || []).map(fixRow);
    const lastId = p.meta && p.meta.insert && AUTO.has(p.meta.insert) && rows[0] ? Number(rows[0].id) : 0;
    return { results: p.meta && p.meta.insert ? [] : rows, success: true, meta: { changes: r.count || 0, last_row_id: lastId }, _ins: p.meta && p.meta.insert && p.meta.ownId && AUTO.has(p.meta.insert) ? p.meta.insert : null };
  }
  // 자동 번호 표에 번호를 직접 넣었으면(복구 · 이관) 다음 번호를 그 뒤로 맞춤
  const fixSeq = async (q, tables) => {
    for (const t of tables) await q("SELECT setval(pg_get_serial_sequence('" + t + "', 'id'), COALESCE((SELECT MAX(id) FROM " + t + "), 0) + 1, false)", []);
  };
  const stmt = (sql, args = []) => ({
    sql, args,
    bind: (...a) => stmt(sql, a),
    async all() { const r = await exec(ex.q, this); if (r._ins) await fixSeq(ex.q, [r._ins]); delete r._ins; return r; },
    async run() { return this.all(); },
    async first(col) { const r = (await exec(ex.q, this)).results; const row = r[0] || null; return col && row ? row[col] : row; },
    async raw() { return (await exec(ex.q, this)).results.map(o => Object.values(o)); }
  });
  return {
    key, driver: 'supabase',
    prepare: sql => stmt(sql),
    // D1 batch = 한 묶음 성공 또는 전부 취소 → PostgreSQL 트랜잭션
    async batch(list) {
      return ex.tx(async q => {
        const out = [], seq = new Set();
        for (const st of list) { const r = await exec(q, st); if (r._ins) seq.add(r._ins); delete r._ins; out.push(r); }
        await fixSeq(q, seq);
        return out;
      });
    }
  };
}
