export function rentUpOf(u) {
  const line = String(u.line).padStart(2, '0');
  const row = RENT_UP.find(r => r[0] === String(u.dong) && r[1] === u.type && r[2].includes(line));
  const b = row && row[3].find(x => u.floor >= x[0] && u.floor <= x[1]);
  return b ? { cur: b[2], next: b[3], up: b[3] - b[2] } : null;
}

// 한 세대 가격 묶음 (없으면 null)
export function priceOf(id) {
  const u = UNIT[id]; if (!u) return null;
  const L = (PRICE[u.dong] || [])[u.line - 1];
  const b = L && L.t === u.type && L.bands.find(x => u.floor >= x[0] && u.floor <= x[1]);
  if (!b) return null;
  const d = DLS[id] || {}, benefit = b[2] * 1e6, dep = d.dep || 0;
  return { id, dong: u.dong, floor: u.floor, line: u.line, type: u.type, terrace: !!b[4], wall: !!d.wall, benefit, hedge: b[3] * 1e6, dep, need: Math.max(benefit - dep, 0), rent: rentUpOf(u) };
}
export const ALL_PRICES = () => UNITS.map(u => priceOf(u.id)).filter(Boolean);
