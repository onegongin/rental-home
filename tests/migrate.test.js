const KEY = 'test-office-code';
let mf;
before(async () => { mf = createTestHarness({ workers: [{ configPath: './wrangler.jsonc', secrets: { STAFF_KEY: KEY, TURNSTILE_SECRET: '' } }] }); await mf.listen(); });
after(() => mf && mf.close());

function agent(ipAddr) {
  const jar = {};
  return async (path, opt = {}) => {
    const headers = { 'content-type': 'application/json', 'cf-connecting-ip': ipAddr };
    const c = Object.entries(jar).map(([k, v]) => k + '=' + v).join('; ');
    if (c) headers.cookie = c;
    const r = await mf.fetch('http://localhost' + path, { method: opt.method || (opt.body ? 'POST' : 'GET'), headers, body: opt.body ? JSON.stringify(opt.body) : undefined });
    (r.headers.getSetCookie ? r.headers.getSetCookie() : []).forEach(s => { const m = s.match(/^([^=]+)=([^;]*)/); if (m) { if (/Max-Age=0/.test(s)) delete jar[m[1]]; else jar[m[1]] = m[2]; } });
    const buf = new Uint8Array(await r.arrayBuffer());
    let json = null; try { json = JSON.parse(new TextDecoder().decode(buf)); } catch (e) {}
    return { status: r.status, json, buf };
  };
}

// node:sqlite 를 D1 모양으로 (되돌림 SQL 시험용)
function sqliteD1() {
  const s = new DatabaseSync(':memory:');
  const st = (sql, a = []) => ({
    sql, a, bind: (...x) => st(sql, x),
    async all() { const p = s.prepare(sql); return /^\s*(SELECT|PRAGMA)/i.test(sql) ? { results: p.all(...a) } : { results: [], meta: { changes: Number(p.run(...a).changes) } }; },
    async run() { return this.all(); },
    async first() { return (await this.all()).results[0] || null; }
  });
  return { key: 'sqlite-test', s, prepare: sql => st(sql), async batch(l) { s.exec('BEGIN'); try { const o = []; for (const x of l) o.push(await x.all()); s.exec('COMMIT'); return o; } catch (e) { s.exec('ROLLBACK'); throw e; } } };
}

test('문법 바꾸기: ? · INSERT OR IGNORE · 별칭 · 빈칸 순서 · 숫자 칸', () => {
  assert.equal(toPg("SELECT * FROM t WHERE a = ? AND b = '?' ORDER BY x DESC, y LIMIT ?").sql, "SELECT * FROM t WHERE a = $1 AND b = '?' ORDER BY x DESC NULLS LAST, y NULLS FIRST LIMIT $2");
  assert.equal(toPg('INSERT OR IGNORE INTO units (id) VALUES (?)').sql, 'INSERT INTO units (id) VALUES ($1) ON CONFLICT DO NOTHING');
  assert.match(toPg('SELECT hash IS NOT NULL AS hasPin FROM staff').sql, /AS "hasPin"/);
  const c = toPg('CREATE TABLE IF NOT EXISTS zz (id INTEGER PRIMARY KEY AUTOINCREMENT, at INTEGER, r REAL)').sql;
  assert.match(c, /rowid BIGSERIAL, id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at NUMERIC, r DOUBLE PRECISION/);
  assert.match(toPg('INSERT INTO zz (at) VALUES (?)').sql, /RETURNING id$/);
});

let file;
test('준비: D1 에 직원 · 상담카드 · 세대 · 감사기록 → 전체 백업 받기', async () => {
  const boss = agent('7.7.7.1');
  await boss('/api/auth/device', { body: { code: KEY } });
  assert.equal((await boss('/api/auth/setup', { body: { name: '대표', pin: '1234' } })).status, 200);
  await boss('/api/admin/staff', { body: { op: 'add', name: '직원이', role: '직원', license: '중개보조원' } });
  const rows = [
    { s: 'c', k: 'c1', v: JSON.stringify({ id: 'c1', name: '홍길동', phone: '010-1234-5678', memo: "따옴표 ' \" 줄바꿈\n이모지 🏠", writer: '대표' }), at: Date.now() },
    { s: 'u', k: '101-1001', v: JSON.stringify({ owner: '김소유', phone: '010-9876-5432', own: { ocType: '전세', ocTen: '이임차', ocTenPh: '010-1111-2222', ocDep: '50000', ocEnd: '2028-01-31' } }), at: Date.now() }
  ];
  assert.equal((await boss('/api/staff/push', { body: { rows } })).status, 200);
  const r = await boss('/api/admin/backup', { body: { op: 'download', pw: 'office-2027' } });
  assert.equal(r.status, 200);
  file = await unpack(r.buf, 'office-2027');
  assert.ok(file.tables.units.rows.length >= 300 && file.tables.tenancies.rows.length >= 1 && file.tables.staff.rows.length === 2);
});

let pgData;
test('기준 6: D1 → Supabase(PostgreSQL) 옮긴 뒤 표마다 건수 · 지문값 100% 같음', async () => {
  const ex = await pgTestExec(), db = pgD1(ex, ex.key);
  const r = await moveInto(db, file);
  assert.ok(r.check.same, r.check.rows.filter(x => !x.ok).map(x => x.t).join(', '));
  assert.ok(r.check.rows.length >= 20, '표 ' + r.check.rows.length + '개');
  // 옮긴 뒤에도 자동 번호가 겹치지 않음 (감사기록 새 줄)
  const max = (await db.prepare('SELECT MAX(id) m FROM audit').first()).m;
  const ins = await db.prepare('INSERT INTO audit (at, who, act) VALUES (?, ?, ?)').bind(Date.now(), '시험', '이관 뒤').run();
  assert.equal(ins.meta.last_row_id, max + 1);
  pgData = await dump(db, '시험');
  pgData.tables.audit.rows.pop();
});

test('반대로: Supabase 백업 → D1(SQLite) 되돌림 SQL → 100% 같음', async () => {
  const db = sqliteD1();
  await init(db); await d1(db).ready();
  db.s.exec(toSqlite(pgData));
  const c = await compare(file, await dump(db, '시험'));
  assert.ok(c.same, c.rows.filter(x => !x.ok).map(x => x.t).join(', '));
});

test('다르면 잡아냄: 한 칸만 바꿔도 그 표가 ✖', async () => {
  const b = JSON.parse(JSON.stringify(file));
  b.tables.persons.rows[0][1] = '바뀐이름';
  const c = await compare(file, b);
  assert.equal(c.same, false);
  assert.deepEqual(c.rows.filter(x => !x.ok).map(x => x.t), ['persons']);
});
